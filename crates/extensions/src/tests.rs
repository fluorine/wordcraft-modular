use serde_json::json;
use wordcraft_engine::{Session, extensions};

fn session() -> Session {
    super::install_all();
    Session::new(wordcraft_doc::Document::new())
}

#[test]
fn installed_extensions_are_compiled_and_registered() {
    let s = session();
    for p in extensions::installed() {
        assert!(extensions::compiled(p.id), "{}", p.id);
        assert!(extensions::get(p.id).is_some(), "{} has no manifest", p.id);
        assert!(s.registry.all().iter().any(|c| c.ext == p.id), "{} registers no command", p.id);
    }
}

#[test]
#[cfg(feature = "mailings")]
fn mailings_commands_run_once_installed() {
    let mut s = session();
    s.run("mailings.start", &json!({"kind": "letters"})).unwrap();
    s.run("extensions.set", &json!({"id": "mailings", "enabled": false})).unwrap();
    assert!(s.run("mailings.start", &json!({"kind": "letters"})).is_err());
}

#[test]
fn installed_commands_survive_hostile_params() {
    let junk = [json!(null), json!({}), json!([]), json!("x"), json!({"path": "/nonexistent/\u{0}"}), json!({"index": -1, "kind": 7})];
    let ids: Vec<&str> = session().registry.all().iter().filter(|c| c.ext != extensions::CORE).map(|c| c.id).collect();
    for id in ids {
        for p in &junk {
            let mut s = session();
            let _ = s.run(id, p);
        }
    }
}

/// The engine's `src/extension_ids.rs`: every extension command's owner, crates included.
#[test]
#[cfg(feature = "full")]
fn extension_ids_are_current() {
    let s = session();
    let mut rows: Vec<(&str, &str)> = s.registry.all().iter().filter(|c| c.ext != extensions::CORE).map(|c| (c.id, c.ext)).collect();
    rows.sort();
    let mut text = String::from("// @generated by `extension_ids_are_current` (WORDCRAFT_UPDATE_IDS=1); do not edit.\n");
    text.push_str("pub const OWNED: &[(&str, &str)] = &[\n");
    for (id, ext) in &rows {
        text.push_str(&format!("    (\"{id}\", \"{ext}\"),\n"));
    }
    text.push_str("];\n");
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../engine/src/extension_ids.rs");
    let current = std::fs::read_to_string(&path).unwrap_or_default().replace("\r\n", "\n");
    if std::env::var("WORDCRAFT_UPDATE_IDS").is_ok() {
        std::fs::write(&path, &text).unwrap();
    } else {
        assert_eq!(current, text, "engine/src/extension_ids.rs is stale: run with WORDCRAFT_UPDATE_IDS=1");
    }
}

#[test]
#[cfg(feature = "full")]
fn every_crate_extension_is_installed() {
    super::install_all();
    for id in extensions::CRATES {
        assert!(extensions::installed().iter().any(|p| p.id == *id), "{id}");
    }
}

#[test]
#[cfg(feature = "full")]
fn parity_floor_with_every_extension() {
    let p = wordcraft_engine::catalog::parity(&session().registry);
    let pct = p["percent"].as_f64().unwrap();
    // The floor only ever rises.
    assert!(pct >= 90.4, "parity {pct}%");
}
